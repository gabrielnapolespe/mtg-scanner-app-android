package com.zaziapps.mtg_scanner.data.model

import android.graphics.RectF
import androidx.compose.runtime.Immutable

/**
 * Immutable state container enclosing the collection of currently active card tracks.
 * Engineered for efficient state allocation and smart recomposition within Jetpack Compose UI layout layers.
 *
 * @property cards The complete collection of active [CardDetection] targets currently tracked within the viewport frame.
 */
@Immutable
data class ScannerState(
    val cards: List<CardDetection> = emptyList()
)


/**
 * Data architecture component tracking an individual card object isolated by the vision system.
 * Encapsulates computer vision tracking metrics along with runtime UI reactive translations.
 *
 * @property id The temporary unique integer identifier assigned to distinguish this object track across consecutive execution frames.
 * @property boundingBox Relative spatial coordinates specifying the position mapping of the card boundary box on screen.
 * @property confidence Precision score indicating the classification accuracy certainty index generated by the machine learning model.
 * @property classId The target category classification index mapping to specific card layout frames.
 * @property framesAlive Count of consecutive frames where the object instance has maintained structural tracking alignment.
 */
data class CardDetection(
    val id: Int,
    val boundingBox: RectF,
    val confidence: Float,
    val classId: Int,

    /** Accumulation counter indicating how many frames this distinct target has been actively verified by the tracking core. */
    var framesAlive: Int = 1
)
